"""Generate test_vectors.inc from the Python reference implementation, so the
C++ encoder is checked byte for byte against it.

    python gen_vectors.py      # rewrites test_vectors.inc next to this file

Values avoid exact .5 rounding ties: Python rounds them to even, C++ away
from zero, and the board accepts either.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "python"))

from openrobot_motor import protocol as P  # noqa: E402

PAR = "MitParams{45.0f, 33.0f, 0.72f, 9.0f, 1}"
PAR4 = "MitParams{45.0f, 33.0f, 0.72f, 9.0f, 4}"
par = P.MitParams(45.0, 33.0, 0.72, 9.0, 1)
par4 = P.MitParams(45.0, 33.0, 0.72, 9.0, 4)

# (C++ expression yielding a Frame, Python bytes)
CASES = [
    ("motor_off()", P.motor_off()),
    ("motor_stop()", P.motor_stop()),
    ("current(1.23f)", P.current(1.23)),
    ("current(-7.7f, 2.34f)", P.current(-7.7, 2.34)),
    ("current(100.0f)", P.current(100.0)),
    ("speed_dps(360.0f)", P.speed_dps(360.0)),
    ("speed_dps(-123.456f)", P.speed_dps(-123.456)),
    ("speed_erpm(-5000.0f)", P.speed_erpm(-5000.0)),
    ("position(-1234.567f)", P.position(-1234.567)),
    ("duty(0.1234f)", P.duty(0.1234)),
    ("duty(-2.0f)", P.duty(-2.0)),
    ("brake(-3.3f)", P.brake(-3.3)),
    ("mit_set_zero(30.01f)", P.mit_set_zero(30.01)),
    ("write_encoder_offset(12345)", P.write_encoder_offset(12345)),
    ("mit_control(0, 0, 0, 0, 0, %s)" % PAR, P.mit_control(0, 0, 0, 0, 0, par)),
    ("mit_control(1.234f, -3.01f, 50.3f, 1.21f, -4.03f, %s)" % PAR,
     P.mit_control(1.234, -3.01, 50.3, 1.21, -4.03, par)),
    ("mit_control(20.0f, 99.0f, 999.0f, 9.0f, 99.0f, %s)" % PAR,
     P.mit_control(20, 99, 999, 9, 99, par)),
    ("mit_control(-0.3f, 0.71f, 12.3f, 7.3f, 0.41f, %s)" % PAR4,
     P.mit_control(-0.3, 0.71, 12.3, 7.3, 0.41, par4)),
]

# (C++ call filling Frame f and returning bool, Python bytes)
CHECKED = [
    ("position_limited(-90.5f, 720.0f, f)", P.position_limited(-90.5, 720)),
    ("write_pid(Pid{0.123f, 0.00456f, 0.00078f}, true, f)",
     P.write_pid(P.Pid(0.123, 0.00456, 0.00078), flash=True)),
    ("write_limits(Limits{18.3f, 40.0f, 15.0f, 3}, f)",
     P.write_limits(P.Limits(18.3, 40.0, 15.0, 3))),
    ("write_mit_params(45.0f, 33.0f, 0.081f, 8.0f, 2, f)",
     P.write_mit_params(45, 33, 0.081, 8.0, 2)),
]


def hexs(b):
    return ", ".join("0x%02X" % x for x in b)


out = ["// Generated by gen_vectors.py from python/openrobot_motor/protocol.py. Do not edit.",
       "struct Vec { Frame got; uint8_t want[8]; const char *name; };",
       "static const Vec VECTORS[] = {"]
for expr, b in CASES:
    out.append('    {%s, {%s}, "%s"},' % (expr, hexs(b), expr.replace('"', "")))
out.append("};")
out.append("struct CVec { bool ok; Frame got; uint8_t want[8]; const char *name; };")
out.append("static CVec checked_vectors(int i) {")
out.append("    Frame f = request(0); bool ok = false;")
out.append("    switch (i) {")
for i, (expr, b) in enumerate(CHECKED):
    out.append("    case %d: ok = %s; { CVec v = {ok, f, {%s}, \"%s\"}; return v; }"
               % (i, expr, hexs(b), expr))
out.append("    }")
out.append("    CVec none = {false, f, {0}, \"\"}; return none;")
out.append("}")
out.append("static const int N_CHECKED = %d;" % len(CHECKED))
open(os.path.join(HERE, "test_vectors.inc"), "w", newline="\n").write("\n".join(out) + "\n")
print("wrote %d + %d vectors" % (len(CASES), len(CHECKED)))
